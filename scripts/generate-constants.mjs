#!/usr/bin/env node
// generate-constants.mjs — generates src/generated/constants.ts from package.json
// Called by: build-portable.ps1 before npx tsc
// Called by: npm run prebuild (dev mode)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');
const srcGenerated = join(repoRoot, 'src', 'generated');

// Parse CLI args: --portable sets IS_PORTABLE_BUILD = true
const isPortable = process.argv.includes('--portable');
const embeddingsEnabled = !process.argv.includes('--no-embeddings');

// Read version from package.json
const pkg = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf-8'));
const version = pkg.version || '0.0.0';

// Ensure directory exists
if (!existsSync(srcGenerated)) {
  mkdirSync(srcGenerated, { recursive: true });
}

// Determine DEV_APP_ROOT_URL
// In dev mode: the repo root URL
// In portable mode: null (WASM grammars are embedded as base64)
const devAppRootUrl = isPortable 
  ? 'null' 
  : `'${new URL('../', import.meta.url).href}'`;

// Generate the file
const content = `// Auto-generated by scripts/generate-constants.mjs — DO NOT EDIT MANUALLY
// Regenerate: node scripts/generate-constants.mjs ${process.argv.slice(2).join(' ')}

/** GitNexus version — read from package.json at generation time */
export const GITNEXUS_VERSION = '${version}';

/** True when built as standalone portable binary via bun build --compile */
export const IS_PORTABLE_BUILD = ${isPortable};

/**
 * App root URL for development mode (null in portable builds).
 * In dev mode: URL pointing to gitnexus/ package root.
 * In portable: null (files are baked into the binary).
 */
export const DEV_APP_ROOT_URL: string | null = ${devAppRootUrl};

/**
 * Whether onnxruntime-node (embeddings) should be enabled.
 * Disabled in portable builds because it's a native .node addon.
 */
export const EMBEDDINGS_ENABLED = ${embeddingsEnabled};
`;

writeFileSync(join(srcGenerated, 'constants.ts'), content, 'utf-8');
console.log(`[generate-constants] Generated constants.ts (version=${version}, portable=${isPortable})`);
